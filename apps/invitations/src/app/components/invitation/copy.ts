export function formatTableLabel(tableName: string, locale: Locale): string {
  const trimmed = tableName.trim();
  if (/^\d+$/.test(trimmed)) {
    if (locale === 'ru') return `Стол № ${trimmed}`;
    if (locale === 'az') return `Masa № ${trimmed}`;
    return `Table No. ${trimmed}`;
  }
  return trimmed;
}
